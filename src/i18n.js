const STRINGS = { en, ar };
let lang = 'en';

export const getLang = () => lang;

export function t(key, vars = {}) {
  const s = STRINGS[lang][key] ?? en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}

export function setLang(next) {
  lang = STRINGS[next] ? next : 'en';
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  for (const el of document.querySelectorAll('[data-i18n]')) {
    const s = t(el.dataset.i18n);
    if (s.includes('<br>')) el.innerHTML = s; else el.textContent = s;
  }
  for (const el of document.querySelectorAll('[data-i18n-attr]')) {
    for (const pair of el.dataset.i18nAttr.split(';')) {
      const [attr, key] = pair.split(':');
      el.setAttribute(attr, t(key));
    }
  }
}

// Dates in the page language, always UTC.
export function fmtDate(ms, withTime = true) {
  const opts = { timeZone: 'UTC', day: 'numeric', month: 'short', year: 'numeric', ...(withTime ? { hour: '2-digit', minute: '2-digit', hourCycle: 'h23' } : {}) };
  return new Intl.DateTimeFormat(lang === 'ar' ? 'ar-EG-u-nu-latn' : 'en-GB', opts).format(ms) + (withTime ? ' UTC' : '');
}
